#!/usr/bin/env python3
"""Generate weather icons for the InkSight-style weather/calendar pages.

The CJK and temperature fonts are WenQuanYi Bitmap Song, produced by
scripts/fonts/wqy_pcf_to_lvgl.py. This script only refreshes the monochrome
weather icons and the asset header that declares both.

Usage (from firmware/):
    python3 scripts/inksight_assets/gen_assets.py --inksight /path/to/inksight

Requires Pillow.
"""

import argparse
import pathlib
import sys

from PIL import Image

FIRMWARE_DIR = pathlib.Path(__file__).resolve().parents[2]
FONT_COMPONENT = FIRMWARE_DIR / "main/components/78__xiaozhi-fonts"
OUT_DIR = FONT_COMPONENT / "src/inksight"
HEADER_PATH = FONT_COMPONENT / "include/inksight_assets.h"

CJK_SIZES = [12, 14, 16]
ICON_NAMES = ["sunny", "partly_cloudy", "cloud", "foggy", "rainy", "snow", "thunderstorm"]
ICON_SIZES = [24, 32]


def icon_bits(path: pathlib.Path, size: int) -> list[int]:
    img = Image.open(path).convert("RGBA")
    if img.size != (size, size):
        img = img.resize((size, size), Image.LANCZOS)
    stride = (size + 7) // 8
    data = [0] * (stride * size)
    for y in range(size):
        for x in range(size):
            r, g, b, a = img.getpixel((x, y))
            if a >= 128 and (r + g + b) / 3 < 160:
                data[y * stride + x // 8] |= 0x80 >> (x % 8)
    return data


def write_icons(icon_dir: pathlib.Path) -> None:
    lines = [
        "/* Generated by scripts/inksight_assets/gen_assets.py. Do not edit. */",
        '#include "inksight_assets.h"',
        "",
    ]
    for size in ICON_SIZES:
        for name in ICON_NAMES:
            data = icon_bits(icon_dir / f"{name}.png", size)
            lines.append(f"static const uint8_t k_{name}_{size}[] = {{")
            for i in range(0, len(data), 16):
                lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
            lines.append("};")
            lines.append("")
        lines.append(f"const inksight_mono_bitmap_t inksight_weather_icons_{size}[INKSIGHT_ICON_COUNT] = {{")
        for name in ICON_NAMES:
            lines.append(f"    {{{size}, {size}, k_{name}_{size}}},")
        lines.append("};")
        lines.append("")
    out = OUT_DIR / "inksight_weather_icons.c"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(FIRMWARE_DIR)}")


def write_header() -> None:
    enum_lines = "\n".join(f"    INKSIGHT_ICON_{n.upper()} = {i}," for i, n in enumerate(ICON_NAMES))
    font_lines = "\n".join(f"extern const struct _lv_font_t inksight_cjk_{s};" for s in CJK_SIZES)
    HEADER_PATH.write_text(f"""/* Generated by scripts/inksight_assets/gen_assets.py. Do not edit.
 * inksight_cjk_* and inksight_temp_48 are generated by scripts/fonts/wqy_pcf_to_lvgl.py.
 */
#pragma once

#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

/* Forward-declared so this header works with both lvgl.h and rawdraw's
 * font_engine.h, which define lv_font_t independently. */
struct _lv_font_t;
{font_lines}
extern const struct _lv_font_t inksight_temp_48;

typedef enum {{
{enum_lines}
    INKSIGHT_ICON_COUNT = {len(ICON_NAMES)},
}} inksight_icon_t;

/* 1bpp, MSB first, rows padded to whole bytes. */
typedef struct {{
    uint16_t width;
    uint16_t height;
    const uint8_t* bits;
}} inksight_mono_bitmap_t;

extern const inksight_mono_bitmap_t inksight_weather_icons_24[INKSIGHT_ICON_COUNT];
extern const inksight_mono_bitmap_t inksight_weather_icons_32[INKSIGHT_ICON_COUNT];

#ifdef __cplusplus
}}
#endif
""", encoding="utf-8")
    print(f"wrote {HEADER_PATH.relative_to(FIRMWARE_DIR)}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inksight", required=True, type=pathlib.Path, help="InkSight repository root")
    args = parser.parse_args()

    icon_dir = args.inksight / "backend/fonts/icons"
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # Text faces are WenQuanYi Bitmap Song. Regenerating them here would
    # replace those bitmaps with Noto.
    write_icons(icon_dir)
    write_header()
    return 0


if __name__ == "__main__":
    sys.exit(main())
