#!/usr/bin/env python3
"""Generate fonts and weather icons for the InkSight-style weather/calendar pages.

Outputs: NotoSerifSC subsets at 12/14/16px (charset collected from the page
sources), a 48px bold temperature font, and the 7 weather icons at 24/32px.

Sources come from an InkSight checkout (backend/fonts). Outputs go to
main/components/78__xiaozhi-fonts/src/inksight/ and its include/ header.

Usage (from firmware/):
    python3 scripts/inksight_assets/gen_assets.py --inksight /path/to/inksight

Requires Pillow and `npx lv_font_conv` (Node.js).
"""

import argparse
import pathlib
import re
import subprocess
import sys

from PIL import Image

FIRMWARE_DIR = pathlib.Path(__file__).resolve().parents[2]
FONT_COMPONENT = FIRMWARE_DIR / "main/components/78__xiaozhi-fonts"
OUT_DIR = FONT_COMPONENT / "src/inksight"
HEADER_PATH = FONT_COMPONENT / "include/inksight_assets.h"

# Every CJK character drawn with inksight_cjk_12 comes from string literals in these files.
CHARSET_SOURCES = [
    "main/common/ink_weather_data.cc",
    "main/common/ink_calendar_data.cc",
    "main/ui/renderers/rawdraw/ink_weather_renderer.cc",
    "main/ui/renderers/rawdraw/ink_calendar_renderer.cc",
]

CJK_SIZES = [12, 14, 16]
TEMP_SYMBOLS = "-0123456789°C"
ICON_NAMES = ["sunny", "partly_cloudy", "cloud", "foggy", "rainy", "snow", "thunderstorm"]
ICON_SIZES = [24, 32]

STRING_LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')


def collect_charset() -> str:
    chars = set(chr(c) for c in range(0x20, 0x7F))
    chars.update("°℃·…，。：、")
    for rel in CHARSET_SOURCES:
        text = (FIRMWARE_DIR / rel).read_text(encoding="utf-8")
        for literal in STRING_LITERAL.findall(text):
            chars.update(ch for ch in literal if ord(ch) > 0x7F)
    return "".join(sorted(chars))


def run_font_conv(font_path: pathlib.Path, size: int, symbols: str, name: str) -> None:
    out = OUT_DIR / f"{name}.c"
    cmd = [
        "npx", "-y", "lv_font_conv",
        "--font", str(font_path),
        "--size", str(size),
        "--bpp", "1",
        "--format", "lvgl",
        "--lv-include", "lvgl.h",
        "--no-compress",
        "--force-fast-kern-format",
        f"--symbols={symbols}",
        "-o", str(out),
    ]
    subprocess.run(cmd, check=True)
    text = out.read_text(encoding="utf-8")
    text = text.replace(str(font_path.parent), "<inksight>/backend/fonts/truetype")
    text = text.replace(str(out.parent), "src/inksight")
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out.relative_to(FIRMWARE_DIR)} ({len(symbols)} glyphs)")


def icon_bits(path: pathlib.Path, size: int) -> list[int]:
    img = Image.open(path).convert("RGBA")
    if img.size != (size, size):
        img = img.resize((size, size), Image.LANCZOS)
    stride = (size + 7) // 8
    data = [0] * (stride * size)
    for y in range(size):
        for x in range(size):
            r, g, b, a = img.getpixel((x, y))
            if a >= 128 and (r + g + b) / 3 < 160:
                data[y * stride + x // 8] |= 0x80 >> (x % 8)
    return data


def write_icons(icon_dir: pathlib.Path) -> None:
    lines = [
        "/* Generated by scripts/inksight_assets/gen_assets.py. Do not edit. */",
        '#include "inksight_assets.h"',
        "",
    ]
    for size in ICON_SIZES:
        for name in ICON_NAMES:
            data = icon_bits(icon_dir / f"{name}.png", size)
            lines.append(f"static const uint8_t k_{name}_{size}[] = {{")
            for i in range(0, len(data), 16):
                lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
            lines.append("};")
            lines.append("")
        lines.append(f"const inksight_mono_bitmap_t inksight_weather_icons_{size}[INKSIGHT_ICON_COUNT] = {{")
        for name in ICON_NAMES:
            lines.append(f"    {{{size}, {size}, k_{name}_{size}}},")
        lines.append("};")
        lines.append("")
    out = OUT_DIR / "inksight_weather_icons.c"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(FIRMWARE_DIR)}")


def write_header() -> None:
    enum_lines = "\n".join(f"    INKSIGHT_ICON_{n.upper()} = {i}," for i, n in enumerate(ICON_NAMES))
    font_lines = "\n".join(f"extern const struct _lv_font_t inksight_cjk_{s};" for s in CJK_SIZES)
    HEADER_PATH.write_text(f"""/* Generated by scripts/inksight_assets/gen_assets.py. Do not edit. */
#pragma once

#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

/* Forward-declared so this header works with both lvgl.h and rawdraw's
 * font_engine.h, which define lv_font_t independently. */
struct _lv_font_t;
{font_lines}
extern const struct _lv_font_t inksight_temp_48;

typedef enum {{
{enum_lines}
    INKSIGHT_ICON_COUNT = {len(ICON_NAMES)},
}} inksight_icon_t;

/* 1bpp, MSB first, rows padded to whole bytes. */
typedef struct {{
    uint16_t width;
    uint16_t height;
    const uint8_t* bits;
}} inksight_mono_bitmap_t;

extern const inksight_mono_bitmap_t inksight_weather_icons_24[INKSIGHT_ICON_COUNT];
extern const inksight_mono_bitmap_t inksight_weather_icons_32[INKSIGHT_ICON_COUNT];

#ifdef __cplusplus
}}
#endif
""", encoding="utf-8")
    print(f"wrote {HEADER_PATH.relative_to(FIRMWARE_DIR)}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inksight", required=True, type=pathlib.Path, help="InkSight repository root")
    args = parser.parse_args()

    fonts_dir = args.inksight / "backend/fonts/truetype"
    icon_dir = args.inksight / "backend/fonts/icons"
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    charset = collect_charset()
    for size in CJK_SIZES:
        run_font_conv(fonts_dir / "NotoSerifSC-Regular.ttf", size, charset, f"inksight_cjk_{size}")
    run_font_conv(fonts_dir / "NotoSerifSC-Bold.ttf", 48, TEMP_SYMBOLS, "inksight_temp_48")
    write_icons(icon_dir)
    write_header()
    return 0


if __name__ == "__main__":
    sys.exit(main())
